function counterEntries(): UserDictEntry[] {
  const out: UserDictEntry[] = [];
  for (const [suffixes, readings] of COUNTERS) {
    NUMERALS.forEach((num, i) => {
      const reading = readings[i];
      if (!reading) return;
      for (const suf of suffixes) {
        out.push({ surface: num + suf, reading });
        const arabic = ARABIC[num];
        if (arabic) out.push({ surface: arabic + suf, reading });
      }
    });
  }
  return out;
}

